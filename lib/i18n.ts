export type Messages = (typeof messages)[Locale];

export function formatSourceInboxBlocker(
  reason: string,
  validation: Messages["sourceInbox"]["validation"],
  invalidDate: string,
) {
  if (reason === invalidDate) return invalidDate;
  const known = new Map([
    ["SourceRecord is not human reviewed.", validation.notReviewed],
    ["SourceRecord is not explicitly approved for daily candidate output.", validation.notApproved],
    ["SourceRecord was rejected during human review.", validation.rejected],
    ["A publishable daily article requires a source URL.", validation.sourceUrl],
    ["A publishable daily article requires a source name or creator.", validation.creator],
    ["SourceRecord has no source body or transcript; use manual recovery first.", validation.body],
    ["SourceRecord has no evidence items.", validation.evidence],
    ["SourceRecord has no reviewed key claims.", validation.claims],
    ["SourceRecord evidence_grade must be assessed before candidate output.", validation.evidenceGrade],
  ]);
  const exact = known.get(reason);
  if (exact) return exact;

  const missingDaily = reason.match(/^Daily candidate metadata is missing ([a-z_]+)\.$/u);
  if (missingDaily) {
    const field = validation.fieldNames[missingDaily[1] as keyof typeof validation.fieldNames];
    return field ? `${validation.dailyMissing}「${field}」。` : validation.generic;
  }
  const missingEnrichment = reason.match(/^Manual enrichment is missing ([a-z_]+)\.$/u);
  if (missingEnrichment) {
    const field = validation.fieldNames[missingEnrichment[1] as keyof typeof validation.fieldNames];
    return field ? `${validation.enrichmentMissing}「${field}」。` : validation.generic;
  }
  const scoreRange = reason.match(/^Daily candidate metadata ([a-z_]+) must be between 1 and 10\.$/u);
  if (scoreRange) {
    const field = validation.fieldNames[scoreRange[1] as keyof typeof validation.fieldNames];
    return field ? validation.dailyScoreRange.replaceAll("{field}", field) : validation.generic;
  }
  if (reason.startsWith("SourceRecord invalid:")) return validation.invalid;
  return validation.generic;
}

export function formatIntelligenceSignal(signal: string, locale: Locale, isRadarFocus = false) {
  const copy = messages[locale].research.intelligence.signals;
  const exact = copy[signal as keyof typeof copy];
  if (exact) return exact;

  const evidenceCount = signal.match(/^(\d+) source evidence item\(s\)$/u);
  if (evidenceCount) return `${evidenceCount[1]} ${copy.sourceEvidenceCount}`;

  const claimCount = signal.match(/^(\d+)\/(\d+) claims have locatable evidence$/u);
  if (claimCount) return `${claimCount[1]}/${claimCount[2]} ${copy.locatableClaimCount}`;

  const evidenceGrade = signal.match(/^human evidence grade (A|B|C|ungraded)$/u);
  if (evidenceGrade) return `${copy.humanEvidenceGrade}: ${evidenceGrade[1]}`;

  const libraryTargets = signal.match(/^(\d+) existing library target\(s\)$/u);
  if (libraryTargets) return `${libraryTargets[1]} ${copy.libraryTargetCount}`;

  return isRadarFocus ? `${copy.matchedRadarFocus}: ${signal}` : signal;
}
